ALTER TABLE conferences              ADD COLUMN organizer_company_id bigint REFERENCES companies (id) ON DELETE SET NULL;
ALTER TABLE admins                   ADD COLUMN company_id           bigint REFERENCES companies (id) ON DELETE RESTRICT;

