-- 1. Байгууллагын төрөл (enum)
CREATE TYPE company_type AS ENUM (
  'llc',              -- ХХК
  'jsc',              -- ХК
  'state_owned',      -- ТӨҮГ / ОНӨҮГ
  'government',       -- Төрийн байгууллага
  'ngo',              -- ТББ
  'cooperative',      -- Хоршоо
  'partnership',      -- Нөхөрлөл
  'sole_proprietor',  -- Хувиараа хөдөлмөр эрхлэгч
  'foreign',          -- Гадаадын хөрөнгө оруулалттай / төлөөлөгчийн газар
  'other'             -- Бусад
);

-- 2. Байгууллагын хүснэгт
CREATE TABLE companies (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text         NOT NULL,
  register_no  text,
  company_type company_type NOT NULL DEFAULT 'other',
  is_active    boolean      NOT NULL DEFAULT true,
  created_at   timestamptz  NOT NULL DEFAULT now(),
  updated_at   timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT chk_company_name_len     CHECK (char_length(btrim(name)) >= 1 AND char_length(name) <= 300),
  CONSTRAINT chk_company_name_trimmed CHECK (name = btrim(name))
);

CREATE UNIQUE INDEX uq_companies_register_no       ON companies (register_no) WHERE register_no IS NOT NULL;
CREATE UNIQUE INDEX uq_companies_name_unregistered ON companies (lower(btrim(name))) WHERE register_no IS NULL;
CREATE INDEX idx_companies_name_trgm               ON companies USING gin (name gin_trgm_ops);
CREATE INDEX idx_companies_active_name             ON companies (name) WHERE is_active;
CREATE INDEX idx_companies_type                    ON companies (company_type);

-- 3. updated_at-ийг автоматаар шинэчлэх trigger
CREATE FUNCTION companies_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END
$$;

CREATE TRIGGER trg_companies_updated_at
  BEFORE UPDATE ON companies
  FOR EACH ROW EXECUTE FUNCTION companies_touch_updated_at();

-- 4. Холбоосууд
ALTER TABLE members                  ADD COLUMN company_id           bigint REFERENCES companies (id) ON DELETE SET NULL;
