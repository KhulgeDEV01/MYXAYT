-- Superadmin нь платформын түвшний админ — байгууллагад харьяалагдахгүй.
ALTER TABLE admins ADD CONSTRAINT chk_superadmin_platform
  CHECK (role <> 'superadmin' OR company_id IS NULL);

-- 5. Санал, бүртгэлд байгууллагыг автоматаар бөглөх trigger-ууд
--    (backend company_id-г өгөөгүй үед гишүүний одоогийн байгууллагыг хуулна)
CREATE FUNCTION ballots_fill_company() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.company_id IS NULL THEN
    SELECT m.company_id INTO NEW.company_id FROM members m WHERE m.id = NEW.member_id;
  END IF;
  IF NEW.company_snapshot IS NULL AND NEW.company_id IS NOT NULL THEN
    SELECT c.name INTO NEW.company_snapshot FROM companies c WHERE c.id = NEW.company_id;
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER trg_ballots_company_fill
  BEFORE INSERT ON ballots
  FOR EACH ROW EXECUTE FUNCTION ballots_fill_company();

CREATE FUNCTION conf_regs_fill_company() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.company_id IS NULL THEN
    SELECT m.company_id INTO NEW.company_id FROM members m WHERE m.id = NEW.member_id;
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER trg_conf_regs_company_fill
  BEFORE INSERT ON conference_registrations
  FOR EACH ROW EXECUTE FUNCTION conf_regs_fill_company();

-- 6. Хуучин текстийг enum болгох туслах функц (зөвхөн энэ migration-д; pg_temp — сесс дуусахад устна)
CREATE FUNCTION pg_temp.to_company_type(raw text) RETURNS company_type
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN v IS NULL OR v = ''                                   THEN 'other'
    WHEN v LIKE '%ХХК%' OR v LIKE '%LLC%'                      THEN 'llc'
    WHEN v LIKE '%ТӨҮГ%' OR v LIKE '%ОНӨҮГ%' OR v LIKE '%ТӨХК%' THEN 'state_owned'
    WHEN v ~ '(^|[^Х])ХК' OR v LIKE '%JSC%'                    THEN 'jsc'
    WHEN v LIKE '%ТББ%' OR v LIKE '%NGO%'                      THEN 'ngo'
    WHEN v LIKE '%ХОРШОО%'                                     THEN 'cooperative'
    WHEN v LIKE '%НӨХӨРЛӨЛ%'                                   THEN 'partnership'
    WHEN v LIKE '%ХУВИАРАА%' OR v LIKE '%ИРГЭН%'               THEN 'sole_proprietor'
    WHEN v LIKE '%ГАДААД%' OR v LIKE '%ТӨЛӨӨЛӨГЧИЙН%'          THEN 'foreign'
    WHEN v LIKE '%ТӨРИЙН%' OR v LIKE '%ЯАМ%' OR v LIKE '%АГЕНТЛАГ%' THEN 'government'
    ELSE 'other'
  END::company_type
  FROM (SELECT upper(btrim(raw)) AS v) s
$$;

-- 7. Одоо байгаа гишүүдийн мэдээллээс байгууллагуудыг үүсгэнэ
--    a) регистрийн дугаартай нь — дугаараар нь нэг байгууллага (зайг арилгана)
INSERT INTO companies (name, register_no, company_type)
SELECT DISTINCT ON (reg)
       left(COALESCE(NULLIF(btrim(company_name), ''), reg), 300),
       reg,
       pg_temp.to_company_type(company_type)
FROM (SELECT *, replace(btrim(org_register), ' ', '') AS reg FROM members) m
WHERE reg <> ''
ORDER BY reg, updated_at DESC;

--    b) регистргүй, зөвхөн нэртэй нь — нэрээр нь (том жижиг үсэг, зай үл хамааран)
INSERT INTO companies (name, company_type)
SELECT DISTINCT ON (lower(btrim(company_name)))
       btrim(left(btrim(company_name), 300)),
       pg_temp.to_company_type(company_type)
FROM members
WHERE NULLIF(replace(btrim(org_register), ' ', ''), '') IS NULL
  AND NULLIF(btrim(company_name), '') IS NOT NULL
  AND lower(btrim(company_name)) NOT IN (SELECT lower(name) FROM companies)
ORDER BY lower(btrim(company_name)), updated_at DESC;

-- 8. Холбоосуудыг бөглөнө
--    гишүүд: эхлээд регистрээр, үлдсэнийг нэрээр
UPDATE members m SET company_id = c.id
FROM companies c
WHERE c.register_no = replace(btrim(m.org_register), ' ', '');

UPDATE members m SET company_id = c.id
FROM companies c
WHERE m.company_id IS NULL
  AND NULLIF(btrim(m.company_name), '') IS NOT NULL
  AND lower(c.name) = lower(btrim(m.company_name));

--    санал ба бүртгэл: гишүүний одоогийн байгууллагаар (company_snapshot текст хэвээр)
UPDATE ballots b SET company_id = m.company_id
FROM members m
WHERE b.member_id = m.id AND m.company_id IS NOT NULL;

UPDATE conference_registrations r SET company_id = m.company_id
FROM members m
WHERE r.member_id = m.id AND m.company_id IS NOT NULL;

--    илтгэгч / ивээн тэтгэгч ба зохион байгуулагч: НЭРЭЭР таарвал (таарахгүй бол NULL, текст нэр хэвээр)
UPDATE conference_people p SET company_id = c.id
FROM companies c
WHERE NULLIF(btrim(p.org_name), '') IS NOT NULL
  AND lower(c.name) = lower(btrim(p.org_name));

UPDATE conferences f SET organizer_company_id = c.id
FROM companies c
WHERE NULLIF(btrim(f.organizer), '') IS NOT NULL
  AND lower(c.name) = lower(btrim(f.organizer));

-- 9. Регистрийн дугаар 7 оронтой тоо байх — хуучин өгөгдлийг шилжүүлсний ДАРАА нэмнэ.
--    NOT VALID: одоо байгаа (хуучин) мөрүүдийг шалгахгүй, цаашид нэмэх / засах мөр бүрийг шалгана.
